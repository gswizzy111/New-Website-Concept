-- Show Dropoffs: cards handed over in person at a card show, taken on the
-- public /show-dropoffs form (no payment, no checkout). Each row is the
-- customer's intake and their signed acceptance of the Terms; the admin later
-- turns it into a regular drop-off order (/admin/show-dropoffs).
-- Additive and rerunnable. Shared by both sites (same database).

create table if not exists show_dropoffs (
  id uuid primary key default gen_random_uuid(),
  dropoff_number integer generated by default as identity (start with 1001) unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  -- Which show (from the form's ?show= link, optional)
  show_name text,

  -- Customer
  customer_name text not null,
  customer_email text not null,
  customer_phone text not null,
  return_address jsonb not null,

  -- What they handed over
  tiers text[] not null default '{}',
  five_plus boolean not null default false,
  card_count integer,
  cards jsonb not null default '[]'::jsonb,
  customer_notes text,

  -- Signed at the table (Terms of Service, E-SIGN consent, optional photo permissions)
  terms_version_id uuid references terms_versions(id),
  terms_version text not null,
  signed_name text not null,
  signed_text text not null,
  signed_sha256 text not null,
  esign_consent boolean not null,
  media_permission boolean not null default false,
  tag_permission boolean not null default false,
  signed_at timestamptz not null default now(),
  ip_address text,
  user_agent text,

  -- Processing (admin)
  status text not null default 'new' check (status in ('new', 'entered', 'cancelled')),
  order_id uuid references orders(id) on delete set null,
  admin_notes text,
  processed_at timestamptz
);

create index if not exists show_dropoffs_status_idx on show_dropoffs(status, created_at desc);
create index if not exists show_dropoffs_email_idx on show_dropoffs(lower(customer_email));

-- Server-side only (service role); no browser access
alter table show_dropoffs enable row level security;

-- The signing time is the database's clock, and what was signed never changes.
-- Only the processing columns (status, order_id, admin_notes, processed_at)
-- may be updated; rows can't be deleted.
create or replace function show_dropoffs_stamp() returns trigger
language plpgsql set search_path = public as $$
begin
  new.created_at := now();
  new.updated_at := now();
  new.signed_at := now();
  return new;
end $$;

create or replace function show_dropoffs_guard() returns trigger
language plpgsql set search_path = public as $$
begin
  if tg_op = 'DELETE' then
    raise exception 'show_dropoffs rows are signed records and cannot be deleted'
      using errcode = 'check_violation';
  end if;
  if (new.id, new.dropoff_number, new.created_at, new.show_name, new.customer_name, new.customer_email,
      new.customer_phone, new.return_address, new.tiers, new.five_plus, new.card_count, new.cards,
      new.customer_notes, new.terms_version_id, new.terms_version, new.signed_name, new.signed_text,
      new.signed_sha256, new.esign_consent, new.media_permission, new.tag_permission, new.signed_at,
      new.ip_address, new.user_agent)
     is distinct from
     (old.id, old.dropoff_number, old.created_at, old.show_name, old.customer_name, old.customer_email,
      old.customer_phone, old.return_address, old.tiers, old.five_plus, old.card_count, old.cards,
      old.customer_notes, old.terms_version_id, old.terms_version, old.signed_name, old.signed_text,
      old.signed_sha256, old.esign_consent, old.media_permission, old.tag_permission, old.signed_at,
      old.ip_address, old.user_agent) then
    raise exception 'Only the status, order and admin notes of a show drop-off can change'
      using errcode = 'check_violation';
  end if;
  new.updated_at := now();
  return new;
end $$;

drop trigger if exists show_dropoffs_stamp on show_dropoffs;
create trigger show_dropoffs_stamp before insert on show_dropoffs
  for each row execute function show_dropoffs_stamp();

drop trigger if exists show_dropoffs_guard on show_dropoffs;
create trigger show_dropoffs_guard before update or delete on show_dropoffs
  for each row execute function show_dropoffs_guard();
